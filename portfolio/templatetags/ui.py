register = template.Library()


@register.simple_tag(takes_context=True)
def language_url(context, lang_code, absolute=False):
    """
    URL de la page courante dans une autre langue (/cours/ ↔ /en/courses/).

    Utilisé pour les balises hreflang et le sélecteur de langue de la barre de navigation.
    """
    request = context.get("request")
    if request is None:
        return ""
    path = translate_url(request.get_full_path(), lang_code)
    if absolute:
        return request.build_absolute_uri(path)
    return path


@register.filter
def star_flags(value):
    """
    4.3 -> [True, True, True, True, False] : une liste de 5 booléens pour dessiner les étoiles.

    Arrondi « classique » (la demi-étoile monte : 3,5 -> 4). On évite round() de Python, qui arrondit
    au pair le plus proche (2,5 -> 2 mais 3,5 -> 4) : incohérent pour afficher une note.
    """
    try:
        filled = max(0, min(5, int(float(value) + 0.5)))
    except (TypeError, ValueError):
        filled = 0
    return [True] * filled + [False] * (5 - filled)


@register.filter
def code_lines(value, width=30):
    """
    Coupe un texte en morceaux d'au plus `width` caractères, aux limites des mots.

    Sert à afficher une longue chaîne comme du code Python lisible (concaténation
    implicite sur plusieurs lignes) : chaque morceau sauf le dernier garde son espace final.
    """
    text = str(value or "").strip()
    if not text:
        return []
    chunks = textwrap.wrap(text, width=int(width), break_long_words=False, break_on_hyphens=False)
    return [chunk + " " for chunk in chunks[:-1]] + chunks[-1:]

