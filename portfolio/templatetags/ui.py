@register.simple_tag
def icon(name, css="h-5 w-5"):
    """Rend une icône SVG inline. Un nom inconnu ne rend rien (jamais d'erreur de template)."""
    if name in STROKE_ICONS:
        return format_html(
            '<svg class="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
            'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{}</svg>',
            css,
            mark_safe(STROKE_ICONS[name]),  # constantes du module : aucune donnée utilisateur
        )
    if name in FILL_ICONS:
        return format_html(
            '<svg class="{}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">'
            '<path d="{}"/></svg>',
            css,
            FILL_ICONS[name],
        )
    return ""
